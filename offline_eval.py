    keys = [
        "AbsRel",
        "RMSE",
        "LogRMSE",
        "Delta1",
        "Delta2",
        "Delta3",
    ]

    means = {
        k: float(np.mean([r[k] for r in rows]))
        for k in keys
    }

    print(f"\n=== Aggregate over {len(rows)} frames ===")

    for k, v in means.items():
        print(f"{k}: {v:.4f}")

    return means

